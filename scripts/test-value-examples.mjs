import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const app = fs.readFileSync(new URL('../app.js', import.meta.url), 'utf8');
const importedExportText = fs.readFileSync(new URL('../data/gwl/blc-curve-export-v1.json', import.meta.url), 'utf8');
const allCurves = JSON.parse(importedExportText).curves;
const curve = allCurves.find(c => c.seriesId === 'world_population_un_1950_2023');
const element = tag => ({tag, children: [], textContent: '', appendChild(child) {this.children.push(child);}});
const text = el => el.textContent + el.children.map(text).join(' ');
const ctx = {allCurves, importedExportText, config: {import: {source: 'data/gwl/blc-curve-export-v1.json'}}, document: {createElement: element}, pointKey: p => `${p.year}:${p.value}`, pointDisplay: (p, unit) => `${p.year} · ${p.display || `${p.value} ${unit}`}`, appendLabeledText: (el, label, value) => {const p = element('p'); p.textContent = label + ': ' + value; el.appendChild(p);}};
const start = app.indexOf('  function importedExampleLocation(');
const end = app.indexOf('  function appendSegmentDataDocumentation(', start);
vm.runInNewContext(app.slice(start, end) + ';this.locate=importedExampleLocation;this.render=appendSegmentValueExample;', ctx);
const segments = [{type: 'observed', points: curve.observations, provenance: curve.observationProvenance}, ...curve.historicalReconstruction.map(s => ({...s, type: 'historical'})), ...curve.projections.map(s => ({...s, type: 'projection'}))];
const lines = importedExportText.split(/\r?\n/);
const pointerValue = path => path.split('/').slice(1).reduce((v, part) => v[part], JSON.parse(importedExportText));
for (const segment of segments) {
  const example = segment.provenance.valueExample;
  const point = segment.points.find(p => p.year === example.year);
  const result = ctx.locate(curve, segment, point);
  assert.match(lines[result.lines.yearLine - 1], new RegExp('"year": ' + point.year));
  assert.ok(lines[result.lines.valueLine - 1].includes('"value": ' + point.value + ','));
  assert.equal(pointerValue(result.pointer + '/value'), point.value);
  assert.ok(result.displayPointer);
  assert.equal(pointerValue(result.displayPointer + '/value'), point.value);
  assert.ok(lines[result.displayLines.valueLine - 1].includes('"value": ' + point.value + ','));
  const panel = element('div');
  ctx.render(panel, curve, segment);
  const output = text(panel);
  assert.ok(output.includes(example.sourceRow));
  assert.ok(output.includes('CSV-Zeile ' + example.sourceLine));
  assert.ok(output.includes('Wert in Zeile ' + result.lines.valueLine));
  assert.ok(output.includes('keine gemeinsame numerische Skala'));
  assert.equal(panel.children[0].children[1].children.length, 4);
  console.log(`${segment.type} ${point.year}: Import-Wertzeile ${result.lines.valueLine}; CSV-Zeile ${example.sourceLine}; Rechnung und sichtbare Punktmarke geprüft.`);
}
const empty = element('div');
ctx.render(empty, curve, {...segments[0], provenance: {}});
assert.equal(empty.children.length, 0);
assert.ok(app.includes('appendSegmentValueExample(details, curve, segment)'));
assert.ok(app.includes('importedExportText = await response.text()'));
console.log('PASS: Vier segmentbezogene Beispiele mit echten JSON-Zeilen, stabilen JSON-Pfaden, Originalzeilen und Umrechnung.');
