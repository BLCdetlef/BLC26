import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const app = fs.readFileSync(new URL('../app.js',import.meta.url),'utf8');
const importedExportText = fs.readFileSync(new URL('../data/gwl/blc-curve-export-v1.json',import.meta.url),'utf8');
const allCurves = JSON.parse(importedExportText).curves;
const curve = allCurves.find(c => c.seriesId === 'global_forest_cover_1992_2022');
const segment = {type:'observed', points:curve.observations, provenance:curve.observationProvenance};
const example = segment.provenance.valueExample;
assert.equal(example.year,1992);
assert.equal(example.sourceValue,60.2);
assert.equal(example.divisor,1);
assert.match(example.sourceLocator,/Seite 95/);
assert.match(example.sourceLocator,/nicht als Zahl/);
assert.match(example.sourceUrl,/#page=95$/);
const el = tag => ({tag,children:[],textContent:'',appendChild(child){this.children.push(child);}});
const text = e => e.textContent + e.children.map(text).join(' ');
const ctx = {allCurves,importedExportText,config:{import:{source:'data/gwl/blc-curve-export-v1.json'}},document:{createElement:el},pointKey:p=>`${p.year}:${p.value}`,pointDisplay:p=>`${p.year} · ${p.display}`,appendLabeledText:(parent,label,value)=>{const child=el('p');child.textContent=label+': '+value;parent.appendChild(child);}};
vm.runInNewContext(app.slice(app.indexOf('  function importedExampleLocation('),app.indexOf('  function appendSegmentDataDocumentation('))+';this.locate=importedExampleLocation;this.render=appendSegmentValueExample;',ctx);
const point = curve.observations[0];
const result = ctx.locate(curve,segment,point);
const lines = importedExportText.split(/\r?\n/);
assert.ok(lines[result.lines.valueLine-1].includes('"value": 60.2,'));
assert.ok(result.displayPointer);
const panel = el('div');ctx.render(panel,curve,segment);
const output = text(panel);
assert.ok(output.includes('60,2 %'));
assert.ok(output.includes('0–100 %'));
assert.ok(output.includes(example.sourceLocator));
assert.ok(output.includes(example.calculationText));
assert.ok(!output.includes('CSV-Zeile undefined'));
assert.ok(!output.includes('Menschen'));
assert.ok(!output.includes('drei Nachkommastellen'));
console.log(`PASS: Landnutzungsbeispiel 1992, Import-Wertzeile ${result.lines.valueLine}, Figure 28 / Seite 95, grafische Näherung und keine Einheitenumrechnung.`);
