import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const app = fs.readFileSync(new URL('../app.js', import.meta.url), 'utf8');
const importedExportText = fs.readFileSync(new URL('../data/gwl/blc-curve-export-v1.json', import.meta.url), 'utf8');
const allCurves = JSON.parse(importedExportText).curves;
const curve = allCurves.find(c => c.seriesId === 'arctic_september_sea_ice_area_1979_2024');
const segment = {type:'observed', points:curve.observations, provenance:curve.observationProvenance};
const example = segment.provenance.valueExample;
const point = segment.points.find(p => p.year === example.year);
assert.equal(example.year, 2024);
assert.equal(example.sourceValue, 3.895940124988556);
assert.equal(point.value, 3.89594);
assert.notEqual(point.value, example.sourceValue);
assert.equal(Number(example.sourceValue.toFixed(example.roundingDigits)), point.value);
assert.match(example.sourceLocator, /nsidc_cdr\[2096\]/);
assert.match(example.sourceUrl, /NorthernHemisphere.*\.nc\?download=1$/);
const el = tag => ({tag,children:[],textContent:'',appendChild(child){this.children.push(child);}});
const text = e => e.textContent + e.children.map(text).join(' ');
const ctx = {allCurves,importedExportText,config:{import:{source:'data/gwl/blc-curve-export-v1.json'}},document:{createElement:el},pointKey:p=>`${p.year}:${p.value}`,pointDisplay:p=>`${p.year} · ${p.display}`,appendLabeledText:(parent,label,value)=>{const child=el('p');child.textContent=label+': '+value;parent.appendChild(child);}};
vm.runInNewContext(app.slice(app.indexOf('  function importedExampleLocation('),app.indexOf('  function appendSegmentDataDocumentation('))+';this.locate=importedExampleLocation;this.render=appendSegmentValueExample;',ctx);
const result = ctx.locate(curve,segment,point);
const lines = importedExportText.split(/\r?\n/);
const pointerValue = path => path.split('/').slice(1).reduce((v, part) => v[part], JSON.parse(importedExportText));
assert.ok(lines[result.lines.valueLine-1].includes('"value": 3.89594,'));
assert.equal(pointerValue(result.pointer + '/value'), point.value);
assert.equal(pointerValue(result.displayPointer + '/value'), point.value);
const panel = el('div');ctx.render(panel,curve,segment);
const output = text(panel);
assert.ok(output.includes('3,90 Mio. km²'));
assert.ok(output.includes(example.sourceLocator));
assert.ok(output.includes(example.calculationText));
assert.ok(output.includes('Wert in Zeile ' + result.lines.valueLine));
assert.ok(!output.includes('CSV-Zeile undefined'));
const mismatch = el('div');
ctx.render(mismatch,curve,{...segment, provenance:{...segment.provenance, valueExample:{...example,sourceValue:4}}});
assert.equal(mismatch.children.length,0);
console.log(`PASS: Meereisbeispiel 2024, Import-Wertzeile ${result.lines.valueLine}, NetCDF-Zeitindex und Rundung geprüft.`);

vm.runInNewContext(app.slice(app.indexOf("  function pointDisplay("),app.indexOf("  function createLegend("))+";this.format=pointDisplay;",ctx);
assert.equal(ctx.format(point,curve.unit),point.display);
assert.equal(ctx.format({year:2024,value:3.89594,display:"2024: 3,90 Mio. km²"},curve.unit),"2024 · 3,90 Mio. km²");
