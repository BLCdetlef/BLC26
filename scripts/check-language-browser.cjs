const { chromium } = require(process.env.BLC_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless: true, executablePath: process.env.BLC_BROWSER_EXECUTABLE});
  try {
    const page = await browser.newPage({viewport: {width: 1440, height: 900}});
    const errors = [];
    const writes = [];
    page.on('pageerror', error => errors.push(error.message));
    // Only read requests are allowed during this regression check.
    await page.route('**/*', route => {
      if (route.request().method() === 'GET') return route.continue();
      writes.push(route.request().method() + ' ' + route.request().url());
      return route.abort();
    });
    await page.goto('http://localhost:3000/?lang=de');
    await page.waitForSelector('.import-status.is-valid');
    const germanPaths = await page.locator('.curve-observed').evaluateAll(paths => paths.map(p => p.getAttribute('d')));
    const count = await page.locator('#seriesCount').textContent();
    await page.locator('#languageSelect').selectOption('en');
    await page.waitForURL('**/*lang=en*');
    await page.waitForSelector('.import-status.is-valid');
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    assert.deepEqual(await page.locator('.curve-observed').evaluateAll(paths => paths.map(p => p.getAttribute('d'))), germanPaths);
    assert.equal(await page.locator('#legendHandle').textContent(), 'Legend');
    assert.equal(await page.locator('#seriesCount').textContent(), count.replace('von', 'of').replace('Kurven', 'curves'));
    await page.locator('#filterHandle').click();
    await page.getByPlaceholder('Search curves or foundations').fill('forest');
    assert.equal(await page.locator('.curve-selection-table tbody tr:visible').count(), 1);
    await page.locator('.curve-selection-table tbody tr:visible input').check();
    await page.getByPlaceholder('Search curves or foundations').fill('');
    assert.equal(await page.locator('.curve-selection-table tbody tr:visible').count(), 28);
    await page.locator('[data-close-panel="filterPanel"]').click();
    await page.locator('#legendHandle').click();
    await page.locator('.legend-series').filter({hasText:'Remaining global forest area'}).click();
    await page.locator('[data-close-panel="legendPanel"]').click();
    assert.ok((await page.locator('#curveDetailContent').innerText()).includes('Data provenance for this segment'));
    const englishPaths = await page.locator('.curve-observed').evaluateAll(paths => paths.map(p => p.getAttribute('d')));
    const englishSelection = await page.locator('.curve-selection-table input:checked').count();
    await page.locator('#languageSelect').selectOption('zh-Hans');
    await page.waitForURL('**/*lang=zh-Hans*');
    await page.waitForSelector('.import-status.is-valid', {state:'attached'});
    assert.equal(await page.locator('html').getAttribute('lang'), 'zh-Hans');
    assert.equal(await page.locator('#legendHandle').textContent(), '图例');
    assert.equal(await page.locator('.curve-selection-table input:checked').count(), englishSelection);
    assert.deepEqual(await page.locator('.curve-observed').evaluateAll(paths => paths.map(p => p.getAttribute('d'))), englishPaths);
    await page.locator('#filterHandle').click();
    await page.getByPlaceholder('搜索曲线或基础领域').fill('森林');
    assert.equal(await page.locator('.curve-selection-table tbody tr:visible').count(), 1);
    await page.getByPlaceholder('搜索曲线或基础领域').fill('');
    await page.getByRole('button', {name:'复制选择链接', exact:true}).click();
    const shareUrl = await page.locator('input[readonly]').inputValue();
    assert.equal(new URL(shareUrl).searchParams.get('lang'), 'zh-Hans');
    await page.locator('[data-close-panel="filterPanel"]').click();
    await page.locator('#legendHandle').click();
    await page.locator('.legend-series').filter({hasText:'全球剩余森林面积'}).click();
    await page.locator('[data-close-panel="legendPanel"]').click();
    assert.ok((await page.locator('#curveDetailContent').innerText()).includes('该分段的数据来源'));
    if (process.env.BLC_LANGUAGE_SCREENSHOT_DIR) {
      await page.locator('#curveDetailContent .curve-data-documentation').evaluate(element => {element.open = true;});
      await page.waitForTimeout(300);
      await page.screenshot({path:require('node:path').join(process.env.BLC_LANGUAGE_SCREENSHOT_DIR, 'blc-chinese-desktop.png'),fullPage:true});
    }
    await page.locator('#languageSelect').selectOption('de');
    await page.waitForURL('**/*lang=de*');
    await page.waitForSelector('.import-status.is-valid', {state:'attached'});
    assert.equal(await page.locator('#legendHandle').textContent(), 'Legende');
    await page.setViewportSize({width:844, height:390});
    await page.goto('http://localhost:3000/?view=zustand&lang=en');
    await page.waitForSelector('.import-status.is-valid', {state:'attached'});
    assert.equal((await page.locator('.embed-full-link').textContent()).trim(), 'Explore all series →');
    await page.goto('http://localhost:3000/?view=zustand&lang=zh-Hans');
    await page.waitForSelector('.import-status.is-valid', {state:'attached'});
    assert.equal((await page.locator('.embed-full-link').textContent()).trim(), '探索所有序列 →');
    const languageBounds = await page.locator('#languageSelect').boundingBox();
    assert.ok(languageBounds.x >= 0 && languageBounds.x + languageBounds.width <= 844);
    if (process.env.BLC_LANGUAGE_SCREENSHOT_DIR) await page.screenshot({path:require('node:path').join(process.env.BLC_LANGUAGE_SCREENSHOT_DIR, 'blc-chinese-mobile.png'),fullPage:true});
    assert.deepEqual(errors, []);
    assert.deepEqual(writes, []);
    console.log('Browser checks passed: DE/EN/zh-Hans, identical chart geometry, preserved selection, English and Chinese search/details/links, embedded mobile view, no write requests or JS errors.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
