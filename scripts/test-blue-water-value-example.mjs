import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const app=fs.readFileSync(new URL('../app.js',import.meta.url),'utf8');
const importedExportText=fs.readFileSync(new URL('../data/gwl/blc-curve-export-v1.json',import.meta.url),'utf8');
const allCurves=JSON.parse(importedExportText).curves;
const curve=allCurves.find(c=>c.seriesId==='blue_water_streamflow');
const segment={type:'observed',points:curve.observations,provenance:curve.observationProvenance};
const example=segment.provenance.valueExample;
const point=segment.points.find(p=>p.year===2019);
assert.equal(point.value,22.84);
assert.equal(Number((example.sourceValue/example.divisor).toFixed(example.roundingDigits)),point.value);
assert.equal(example.sourceLine,120);
assert.equal(example.sourceColumnNumber,6);
const el=tag=>({tag,children:[],textContent:'',appendChild(child){this.children.push(child);}});
const text=e=>e.textContent+e.children.map(text).join(' ');
const ctx={allCurves,importedExportText,config:{import:{source:'data/gwl/blc-curve-export-v1.json'}},document:{createElement:el},pointKey:p=>`${p.year}:${p.value}`,appendLabeledText:(parent,label,value)=>{const child=el('p');child.textContent=label+': '+value;parent.appendChild(child);}};
vm.runInNewContext(app.slice(app.indexOf('  function pointDisplay('),app.indexOf('  function createLegend(')),ctx);
vm.runInNewContext(app.slice(app.indexOf('  function importedExampleLocation('),app.indexOf('  function appendSegmentDataDocumentation('))+';this.locate=importedExampleLocation;this.render=appendSegmentValueExample;',ctx);
const location=ctx.locate(curve,segment,point);
const lines=importedExportText.split(/\r?\n/);
const pointerValue=path=>path.split('/').slice(1).reduce((v,part)=>v[part],JSON.parse(importedExportText));
assert.match(lines[location.lines.valueLine-1], /"value": 22\.84\s*,?$/);
assert.equal(pointerValue(location.pointer+'/value'),point.value);
assert.equal(pointerValue(location.displayPointer+'/value'),point.value);
const panel=el('div');ctx.render(panel,curve,segment);const output=text(panel);
assert.ok(output.includes('22,84 %'));
assert.ok(output.includes('CSV-Zeile 120'));
assert.ok(output.includes('Spalte 6 „ensemble_median“'));
assert.ok(output.includes(example.sourceHeader));
assert.ok(output.includes(example.sourceRow));
assert.ok(output.includes(example.calculationText));
assert.ok(output.includes('Wert in Zeile '+location.lines.valueLine));
assert.ok(!output.includes('Entity=World'));
assert.ok(!output.includes('undefined'));
console.log('PASS: Blauwasser-Messwertbeispiel 2019, Import-Wertzeile '+location.lines.valueLine+', Originalzeile und Rechnung angezeigt.');
